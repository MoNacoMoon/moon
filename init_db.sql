-- Скрипт создания базы данных и таблиц для ПР 8-9 (PostgreSQL)

DROP TABLE IF EXISTS "Пользователь";
DROP TABLE IF EXISTS "СекретныйВопрос";

-- Таблица: СекретныйВопрос
CREATE TABLE "СекретныйВопрос" (
    "КодСекретногоВопроса" INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "СекретныйВопрос1" VARCHAR(100) NOT NULL
);

-- Таблица: Пользователь
CREATE TABLE "Пользователь" (
    "КодПользователя" INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "Фамилия" VARCHAR(50) NOT NULL,
    "Имя" VARCHAR(50) NOT NULL,
    "ЭлектроннаяПочта" VARCHAR(50) NOT NULL,
    "Пароль" VARCHAR(50) NOT NULL,
    "КодовоеСлово" VARCHAR(50) NOT NULL,
    "ОтветНаСекретныйВопрос" VARCHAR(50) NOT NULL,
    "КодСекретногоВопроса" INT NOT NULL REFERENCES "СекретныйВопрос"("КодСекретногоВопроса")
);

